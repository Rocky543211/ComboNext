function ComboNextL(key, ...)
    local language = "en";
    local languageApi = Turbine.Language;
    local ok, current = pcall(Turbine.Engine.GetLanguage);
    if (ok and languageApi) then
        if (languageApi.German ~= nil and current == languageApi.German) then
            language = "de";
        elseif (languageApi.French ~= nil and current == languageApi.French) then
            language = "fr";
        end
    end
    local text = translations[language][key] or translations.en[key] or key;
    if (select("#", ...) > 0) then
        local fine, result = pcall(string.format, text, ...);
        return fine and result or text;
    end
    return text;
end
